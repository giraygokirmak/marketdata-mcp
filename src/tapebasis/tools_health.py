"""Ops tools: provider health, drift report and a self-describing tool map."""
from __future__ import annotations

from typing import Any

from .health import FINVIZ, MONITOR, TRADINGVIEW
from .providers_state import DataProvider, envelope

READ_ONLY = {"readOnlyHint": True, "destructiveHint": False, "openWorldHint": True}


async def tapebasis_health(refresh: bool = False) -> dict[str, Any]:
    """Probe both upstreams and report whether either provider's API drifted.

    Every other tool reads the cached verdict from this monitor and adds a
    warning when a provider's upstream schema has changed or is down. Call this
    with ``refresh=True`` to force an immediate re-probe (otherwise the cached
    result is reused for ``TAPEBASIS_HEALTH_TTL`` seconds).

    Args:
        refresh: Force fresh probes instead of using the cached verdict.

    Returns:
        Envelope whose ``data`` carries ``providers`` (``OK``/``DRIFT``/
        ``DOWN``/``UNKNOWN`` per provider), ``degraded``, ``issues`` and the
        per-probe baseline comparison.
    """
    MONITOR.ensure_started()
    if refresh or not MONITOR.results:
        await MONITOR.run_once(force=True)

    summary = MONITOR.summary()
    statuses = summary["providers"]
    responding = [name for name, status in statuses.items() if status in ("OK", "DRIFT")]
    if len(responding) == 2:
        provider = DataProvider.BOTH
    elif responding == [TRADINGVIEW]:
        provider = DataProvider.TRADINGVIEW
    elif responding == [FINVIZ]:
        provider = DataProvider.FINVIZ
    else:
        provider = DataProvider.NONE

    warnings = [
        f"{issue['provider']} {issue['status']}: {issue['probe']} — {issue['message']}"
        for issue in summary["issues"]
    ]
    if summary["degraded"]:
        statuses_note = (
            "Provider health problem detected. Any tool response will carry this "
            "warning until the upstream is fixed or recovered."
        )
        warnings.insert(0, statuses_note)

    return envelope(
        summary,
        provider=provider,
        warnings=warnings,
        degraded=summary["degraded"],
        sources={name: "health probe" for name in statuses},
        extra={"schema_drift": summary["issues"]},
    )


async def tapebasis_tool_map() -> dict[str, Any]:
    """List every tool, which providers back it, and how it is cross-checked.

    Useful for an agent that needs to know whether a given capability is
    dual-sourced (``BOTH``), single-sourced (``TRADINGVIEW``/``FINVIZ``) or
    analysis generated by one provider only. This tool performs no upstream
    requests.
    """
    from .catalog import TOOL_CATALOG

    rows = [dict(row) for row in TOOL_CATALOG]
    counts: dict[str, int] = {}
    for row in rows:
        counts[row["providers"]] = counts.get(row["providers"], 0) + 1
    return envelope(
        {"tools": rows, "count": len(rows), "by_provider": counts},
        provider=DataProvider.BOTH,
        fields={row["name"]: DataProvider.BOTH for row in rows},
        warnings=MONITOR.warnings_for(("BOTH",)),
        degraded=MONITOR.degraded(),
        sources={"catalog": "local tool metadata"},
    )


def register(mcp) -> int:
    """Register this module's tools on *mcp*; returns the number added."""
    mcp.add_tool(
        tapebasis_health,
        name="tapebasis_health",
        title="Provider Health & Schema Drift",
        description=tapebasis_health.__doc__,
    )
    mcp.add_tool(
        tapebasis_tool_map,
        name="tapebasis_tool_map",
        title="Tool / Provider Map",
        description=tapebasis_tool_map.__doc__,
    )
    return 2
